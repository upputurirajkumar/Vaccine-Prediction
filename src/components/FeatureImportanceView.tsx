import React, { useState } from 'react';
import { TOP_FEATURE_IMPORTANCE } from '../data/modelData';
import { 
  BarChart3, 
  HelpCircle, 
  Sparkles, 
  Stethoscope, 
  ShieldAlert, 
  Users, 
  HeartPulse, 
  ArrowRight
} from 'lucide-react';

export const FeatureImportanceView: React.FC = () => {
  const [selectedCategory, setSelectedCategory] = useState<string>('All');
  const [activeFeature, setActiveFeature] = useState(TOP_FEATURE_IMPORTANCE[0]);

  const categories = ['All', 'Healthcare', 'Beliefs & Opinions', 'Demographics', 'Behavioral'];

  const filteredFeatures = selectedCategory === 'All'
    ? TOP_FEATURE_IMPORTANCE
    : TOP_FEATURE_IMPORTANCE.filter(f => f.category === selectedCategory);

  const getCategoryIcon = (category: string) => {
    switch (category) {
      case 'Healthcare':
        return <Stethoscope className="w-3.5 h-3.5 text-teal-600" />;
      case 'Beliefs & Opinions':
        return <ShieldAlert className="w-3.5 h-3.5 text-indigo-600" />;
      case 'Demographics':
        return <Users className="w-3.5 h-3.5 text-amber-600" />;
      case 'Behavioral':
        return <HeartPulse className="w-3.5 h-3.5 text-rose-600" />;
      default:
        return null;
    }
  };

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="bg-white rounded-2xl border border-slate-200 shadow-xs p-6">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div>
            <h2 className="text-xl font-bold text-slate-900 flex items-center gap-2">
              <BarChart3 className="w-5 h-5 text-teal-600" />
              Machine Learning Feature Attribution &amp; Importance
            </h2>
            <p className="text-sm text-slate-600 mt-1">
              Gini impurity reduction and gain-based feature rankings generated by the winning XGBoost and Gradient Boosting models.
            </p>
          </div>

          {/* Filter Pills */}
          <div className="flex flex-wrap gap-1.5 self-start md:self-auto">
            {categories.map((cat) => (
              <button
                key={cat}
                onClick={() => setSelectedCategory(cat)}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
                  selectedCategory === cat
                    ? 'bg-teal-600 text-white shadow-xs'
                    : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                }`}
              >
                {cat}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Main Content Grid: Importance Chart (7 cols) + Feature Detail Card (5 cols) */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Horizontal Bar Chart (7 cols) */}
        <div className="lg:col-span-7 bg-white rounded-2xl border border-slate-200 shadow-xs p-6">
          <div className="flex items-center justify-between mb-4 pb-3 border-b border-slate-100">
            <span className="text-xs font-bold uppercase tracking-wider text-slate-500">
              Ranked Predictors (Relative Gain Weight)
            </span>
            <span className="text-xs text-slate-400">Click bar to inspect details</span>
          </div>

          <div className="space-y-3.5">
            {filteredFeatures.map((item, idx) => {
              const isSelected = activeFeature.feature === item.feature;
              const percentWidth = (item.importance / TOP_FEATURE_IMPORTANCE[0].importance) * 100;

              return (
                <div
                  key={item.feature}
                  onClick={() => setActiveFeature(item)}
                  className={`p-2.5 rounded-xl transition-all cursor-pointer border ${
                    isSelected
                      ? 'bg-teal-50/80 border-teal-300 shadow-xs'
                      : 'border-transparent hover:bg-slate-50 hover:border-slate-200'
                  }`}
                >
                  <div className="flex items-center justify-between text-xs mb-1.5">
                    <div className="flex items-center gap-2">
                      <span className="font-bold text-slate-400 w-4">#{idx + 1}</span>
                      <span className="font-semibold text-slate-900">{item.displayName}</span>
                      <span className="inline-flex items-center gap-1 text-[10px] font-medium text-slate-500 bg-slate-100 px-1.5 py-0.5 rounded">
                        {getCategoryIcon(item.category)}
                        {item.category}
                      </span>
                    </div>
                    <span className="font-mono font-bold text-teal-700">
                      {(item.importance * 100).toFixed(1)}%
                    </span>
                  </div>

                  {/* Horizontal Bar */}
                  <div className="w-full bg-slate-100 h-2.5 rounded-full overflow-hidden">
                    <div
                      className={`h-full rounded-full transition-all duration-500 ${
                        isSelected
                          ? 'bg-gradient-to-r from-teal-500 to-emerald-500'
                          : 'bg-teal-600/70'
                      }`}
                      style={{ width: `${percentWidth}%` }}
                    />
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* Feature Detail Inspector & What-If Simulator (5 cols) */}
        <div className="lg:col-span-5 space-y-6">
          {/* Feature Deep Dive Card */}
          <div className="bg-white rounded-2xl border border-slate-200 shadow-xs p-6">
            <div className="flex items-center justify-between mb-3">
              <span className="inline-flex items-center gap-1 text-xs font-semibold px-2.5 py-1 rounded-full bg-teal-50 text-teal-700 border border-teal-200">
                {getCategoryIcon(activeFeature.category)}
                {activeFeature.category}
              </span>
              <span className="text-xs font-mono font-bold text-slate-500">
                Importance: {(activeFeature.importance * 100).toFixed(1)}%
              </span>
            </div>

            <h3 className="text-lg font-bold text-slate-900 mb-2">
              {activeFeature.displayName}
            </h3>

            <p className="text-sm text-slate-600 leading-relaxed mb-4">
              {activeFeature.description}
            </p>

            <div className="bg-slate-50 p-3.5 rounded-xl border border-slate-200 text-xs text-slate-700 space-y-2">
              <div className="font-semibold text-slate-900 flex items-center gap-1.5">
                <Sparkles className="w-4 h-4 text-teal-600" />
                Clinical Practice Takeaway:
              </div>
              {activeFeature.feature === 'doctor_recc_h1n1' && (
                <p>
                  A patient whose primary doctor advises receiving the H1N1 vaccine has an odds ratio over 8x higher of vaccination compared to one without. Active physician counseling is the highest-ROI public health lever.
                </p>
              )}
              {activeFeature.feature === 'opinion_h1n1_risk' && (
                <p>
                  Individuals who perceive themselves as low-risk rarely seek vaccination spontaneously. Campaigns emphasizing risk to loved ones and vulnerable family members effectively raise protective action.
                </p>
              )}
              {activeFeature.feature === 'opinion_h1n1_vacc_effective' && (
                <p>
                  Belief in efficacy directly mirrors uptake. Communicating clear, transparent clinical trial numbers and real-world hospital admission reductions rebuilds public trust.
                </p>
              )}
              {activeFeature.feature !== 'doctor_recc_h1n1' &&
                activeFeature.feature !== 'opinion_h1n1_risk' &&
                activeFeature.feature !== 'opinion_h1n1_vacc_effective' && (
                  <p>
                    Addressing structural access, financial coverage, and targeted community interventions drives incremental coverage gains towards herd immunity.
                  </p>
                )}
            </div>
          </div>

          {/* Three Key Insights Summary Card */}
          <div className="bg-gradient-to-br from-slate-900 to-teal-950 text-white rounded-2xl p-6 shadow-md">
            <h4 className="font-bold text-base mb-3 flex items-center gap-2">
              <HelpCircle className="w-5 h-5 text-teal-400" />
              Summary of Model Findings
            </h4>

            <div className="space-y-3 text-xs text-slate-300">
              <div className="flex gap-2">
                <span className="font-bold text-teal-400">1.</span>
                <p>
                  <strong>Physicians are Gatekeepers:</strong> Clinical recommendation dwarfs demographic variables like race, gender, or income.
                </p>
              </div>
              <div className="flex gap-2">
                <span className="font-bold text-teal-400">2.</span>
                <p>
                  <strong>Risk Perception Trumps General Concern:</strong> Personal perceived vulnerability is far more predictive than abstract worry about outbreaks.
                </p>
              </div>
              <div className="flex gap-2">
                <span className="font-bold text-teal-400">3.</span>
                <p>
                  <strong>Side Effect Fears are Solvable:</strong> Education contrasting mild soreness with severe influenza morbidity mitigates refusal rates.
                </p>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
